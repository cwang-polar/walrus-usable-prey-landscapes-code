def gini(values: Sequence[float]) -> float:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    arr = arr[arr >= 0]
    if arr.size == 0:
        return float("nan")
    if np.all(arr == 0):
        return 0.0
    arr_sorted = np.sort(arr)
    n = arr_sorted.size
    cumulative = np.cumsum(arr_sorted)
    return float((n + 1 - 2 * np.sum(cumulative) / cumulative[-1]) / n)


def df_to_grid(df: pd.DataFrame, value_col: str, x_col: str = "grid_x", y_col: str = "grid_y") -> np.ndarray:
    """Convert long grid-cell table to 2D array."""

    return (
        df.pivot(index=y_col, columns=x_col, values=value_col)
        .sort_index(axis=0)
        .sort_index(axis=1)
        .values
    )


def ice_df_to_grid(df: pd.DataFrame, value_col: str = "A_mean") -> np.ndarray:
    return (
        df.pivot(index="y_idx", columns="x_idx", values=value_col)
        .sort_index(axis=0)
        .sort_index(axis=1)
        .values
    )


def window_mid_year(label: str) -> float:
    start, end = map(int, label.split("_"))
    return 0.5 * (start + end)


def get_early_late_windows(surface_dict: Mapping[str | tuple[int, int], pd.DataFrame]) -> tuple[object, object]:
    """Return first and last window keys by mid-year."""

    def key_mid(key) -> float:
        if isinstance(key, tuple):
            return 0.5 * (key[0] + key[1])
        return window_mid_year(str(key))

    keys = sorted(surface_dict, key=key_mid)
    return keys[0], keys[-1]


