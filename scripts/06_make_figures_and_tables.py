def summarize_ice_for_site(
    ice_surfaces_dict: Mapping[str | tuple[int, int], pd.DataFrame],
    site_name: str,
) -> pd.DataFrame:
    """Summarize mean A_ice and Gini(A_ice) across windows."""

    rows = []
    for key, df in ice_surfaces_dict.items():
        label = f"{key[0]}_{key[1]}" if isinstance(key, tuple) else str(key)
        rows.append(
            {
                "site": site_name,
                "window": label,
                "mid_year": window_mid_year(label),
                "mean_A": float(df["A_mean"].mean()),
                "gini_A": gini(df["A_mean"]),
            }
        )
    return pd.DataFrame(rows).sort_values("mid_year").reset_index(drop=True)


