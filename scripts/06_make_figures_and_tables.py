def generate_full_ice_sensitivity_table(
    site: str,
    all_windows: Sequence[str],
    base_dir: str | Path,
    ice_dict: Mapping[str, pd.DataFrame],
    betas: Sequence[float] = (0.3, 0.5, 0.8),
    species_cols: Sequence[str] = DEFAULT_SPECIES_COLS,
) -> pd.DataFrame:
    """Appendix Table S1: biomass and attainable fraction for beta values."""

    rows = []
    for window in all_windows:
        path = Path(base_dir) / f"{site}_surfaces" / f"{site}_surface_{window}.csv"
        if not path.exists() or window not in ice_dict:
            continue
        df = pd.read_csv(path)
        pure_total = float(df[list(species_cols)].sum(axis=1).sum())
        merged = df.merge(
            ice_dict[window][["y_idx", "x_idx", "A_mean"]],
            left_on=["grid_y", "grid_x"],
            right_on=["y_idx", "x_idx"],
            how="left",
        )
        merged["A_mean"] = merged["A_mean"].fillna(0.0).clip(0.0, 1.0)
        for beta in betas:
            a_beta = 1.0 - beta * (1.0 - merged["A_mean"])
            adjusted = sum((merged[col] * a_beta).sum() for col in species_cols)
            rows.append(
                {
                    "Site": site,
                    "Time Interval": window.replace("_", "-"),
                    "Sensitivity (beta)": beta,
                    "Total biomass": round(pure_total, 1),
                    "Ice-adjusted biomass": round(float(adjusted), 1),
                    "Maximum attainable fraction (%)": round(100 * adjusted / pure_total, 1) if pure_total > 0 else np.nan,
                }
            )
    return pd.DataFrame(rows)


def build_table_s1_ice_sensitivity(
    site: str,
    all_windows: Sequence[str],
    base_dir: str | Path,
    ice_dict: Mapping[str, pd.DataFrame],
    betas: Sequence[float] = (0.3, 0.5, 0.8),
    species_cols: Sequence[str] = DEFAULT_SPECIES_COLS,
) -> pd.DataFrame:
    """Appendix Table S1: functional biomass and attainable fraction by beta."""

    return generate_full_ice_sensitivity_table(
        site=site,
        all_windows=all_windows,
        base_dir=base_dir,
        ice_dict=ice_dict,
        betas=betas,
        species_cols=species_cols,
    )


def create_publication_ready_station_table(input_csv: str | Path, output_excel: str | Path) -> pd.DataFrame:
    """Format station-level prey data as a supplementary station table."""

    df = pd.read_csv(input_csv)
    sp_cols = ["mean_gc_Polychaeta_1", "mean_gc_Bivalvia_1", "mean_gc_Sipuncula_1"]
    df["Total_gC_Biomass"] = df[sp_cols].sum(axis=1).round(2)
    df["Dominant_Fauna"] = (
        df[sp_cols]
        .idxmax(axis=1)
        .str.replace("mean_gc_", "", regex=False)
        .str.replace("_1", "", regex=False)
    )
    final = pd.DataFrame(
        {
            "Station (Grid Cell)": df["GridCellNme"],
            "Latitude": df["Latitude_Center"].round(4),
            "Longitude": df["Longitude_Center"].round(4),
            "Sampling Year": df["DataYear"],
            "Total Biomass (gC/m2)": df["Total_gC_Biomass"],
            "Dominant Faunal Type": df["Dominant_Fauna"],
        }
    ).sort_values(["Sampling Year", "Station (Grid Cell)"])
    final.to_excel(output_excel, index=False)
    return final


