def plot_main_text_ship_precise_fixed(
    df_ice_only: pd.DataFrame,
    df_ship_ice: pd.DataFrame,
    pure_dict: Mapping[str, Sequence[Mapping[str, object]]],
    df_exact_ice_ceilings: pd.DataFrame,
    df_exact_ship_ceilings: pd.DataFrame,
    site_name: str,
    ship_windows: Sequence[str],
    beta_main: float = 0.5,
    alpha_main: float = 0.5,
    savepath: str | Path | None = None,
):
    """Manuscript Figure 5 lower panels: pure, ice-only, and ice+ship curves."""

    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(ship_windows), figsize=(5 * len(ship_windows), 5), sharey=True)
    if len(ship_windows) == 1:
        axes = [axes]
    for ax, window in zip(axes, ship_windows):
        t_pure, a_pure = get_pure_robust(pure_dict, window)
        t_ice, a_ice = get_ship_ice_robust(df_ice_only, site_name, beta_main, 0.0, window)
        t_ship, a_ship = get_ship_ice_robust(df_ship_ice, site_name, beta_main, alpha_main, window)

        row_ice = df_exact_ice_ceilings[
            (df_exact_ice_ceilings["Site"] == site_name)
            & (df_exact_ice_ceilings["Window"] == window)
            & np.isclose(df_exact_ice_ceilings["Beta"], beta_main)
        ]
        row_ship = df_exact_ship_ceilings[
            (df_exact_ship_ceilings["Site"] == site_name)
            & (df_exact_ship_ceilings["Window"] == window)
            & np.isclose(df_exact_ship_ceilings["Beta"], beta_main)
            & np.isclose(df_exact_ship_ceilings["Alpha"], alpha_main)
        ]
        ice_ceil = row_ice["Exact_Ceiling"].values[0] * 100 if not row_ice.empty else np.nan
        ship_ceil = row_ship["Exact_Ceiling"].values[0] * 100 if not row_ship.empty else np.nan

        if len(t_pure):
            ax.plot(t_pure * 100, a_pure * 100, color="black", marker="o", label="Pure biomass")
        if len(t_ice):
            ax.plot(t_ice * 100, a_ice * 100, color="#1f77b4", marker="s", linestyle="--", label=f"Ice-adjusted (beta={beta_main})")
        if len(t_ship):
            ax.plot(t_ship * 100, a_ship * 100, color="#d62728", marker="^", linestyle="-.", label=f"Ice + ship (alpha={alpha_main})")
        if np.isfinite(ice_ceil) and ice_ceil < 99:
            ax.axvline(ice_ceil, color="#1f77b4", linestyle=":", linewidth=1.5)
        if np.isfinite(ship_ceil) and ship_ceil < 99:
            ax.axvline(ship_ceil, color="#d62728", linewidth=1.5)
            ax.axvspan(ship_ceil, 105, color="#d62728", alpha=0.1)

        ax.set_title(window.replace("_", "-"))
        ax.set_xlabel("Target biomass threshold (%)")
        ax.set_xlim(0, 102)
        ax.set_ylim(0, 105)
        ax.grid(True, linestyle=":", alpha=0.6)
        if ax == axes[0]:
            ax.set_ylabel("Minimum area required (% of site)")
            ax.legend(frameon=True, framealpha=0.9)
    plt.tight_layout()
    if savepath is not None:
        plt.savefig(savepath, dpi=600, bbox_inches="tight")
    return fig, axes


