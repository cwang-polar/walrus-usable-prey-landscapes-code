def extract_curve(curve_list: Sequence[Mapping[str, object]]) -> tuple[np.ndarray, np.ndarray]:
    """Extract feasible threshold and area-fraction arrays from curve records."""

    pairs = []
    for row in curve_list:
        if str(row.get("feasible", True)) == "False":
            continue
        area = row.get("area_fraction")
        if area is None:
            continue
        area_float = float(area)
        if np.isfinite(area_float):
            pairs.append((float(row["threshold"]), area_float))
    if not pairs:
        return np.array([]), np.array([])
    pairs = sorted(pairs)
    return np.array([p[0] for p in pairs]), np.array([p[1] for p in pairs])


def get_curve_robust(df_all: pd.DataFrame, site: str, beta: float, window: str) -> tuple[np.ndarray, np.ndarray]:
    """Extract ice-only curve arrays from long-form curve table."""

    mask = (
        (df_all["Site"] == site)
        & np.isclose(df_all["Beta"], beta)
        & (df_all["Window"] == window)
    )
    subset = df_all[mask].copy()
    if subset.empty:
        return np.array([]), np.array([])
    if subset["Feasible"].dtype == object:
        subset["Feasible"] = subset["Feasible"].astype(str) == "True"
    valid = subset[subset["Feasible"]].sort_values("Threshold_Pct")
    return valid["Threshold_Pct"].values, valid["Min_Area_Ratio"].values


def get_ship_ice_robust(
    df_all: pd.DataFrame,
    site: str,
    beta: float,
    alpha: float,
    window: str,
) -> tuple[np.ndarray, np.ndarray]:
    """Extract ice+ship curve arrays from long-form curve table."""

    mask = (
        (df_all["Site"] == site)
        & np.isclose(df_all["Beta"], beta)
        & np.isclose(df_all["Alpha"], alpha)
        & (df_all["Window"] == window)
    )
    subset = df_all[mask].copy()
    if subset.empty:
        return np.array([]), np.array([])
    if subset["Feasible"].dtype == object:
        subset["Feasible"] = subset["Feasible"].astype(str) == "True"
    valid = subset[subset["Feasible"]].sort_values("Threshold_Pct")
    return valid["Threshold_Pct"].values, valid["Min_Area_Ratio"].values


def get_pure_robust(pure_dict: Mapping[str, Sequence[Mapping[str, object]]], window: str) -> tuple[np.ndarray, np.ndarray]:
    if window not in pure_dict:
        return np.array([]), np.array([])
    return extract_curve(pure_dict[window])


def plot_main_text_final(
    df_curves_all: pd.DataFrame,
    pure_curves_dict: Mapping[str, Sequence[Mapping[str, object]]],
    site_name: str,
    windows_to_plot: Sequence[str],
    beta_main: float = 0.5,
    savepath: str | Path | None = None,
):
    """Manuscript Figure 5 upper panels: pure vs ice-adjusted curves."""

    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(windows_to_plot), figsize=(5 * len(windows_to_plot), 5), sharey=True)
    if len(windows_to_plot) == 1:
        axes = [axes]
    for ax, window in zip(axes, windows_to_plot):
        t_pure, a_pure = get_pure_robust(pure_curves_dict, window)
        t_ice, a_ice = get_curve_robust(df_curves_all, site_name, beta_main, window)
        if len(t_pure):
            ax.plot(t_pure * 100, a_pure * 100, color="black", marker="o", label="Pure biomass")
        if len(t_ice):
            ax.plot(t_ice * 100, a_ice * 100, color="#1f77b4", marker="s", linestyle="--", label=f"Ice-adjusted (beta={beta_main})")
        ax.set_title(window.replace("_", "-"))
        ax.set_xlabel("Target biomass threshold (%)")
        ax.set_xlim(0, 105)
        ax.set_ylim(0, 105)
        ax.grid(True, linestyle=":", alpha=0.6)
        if ax == axes[0]:
            ax.set_ylabel("Minimum area required (% of site)")
            ax.legend(frameon=True, framealpha=0.9)
    plt.tight_layout()
    if savepath is not None:
        plt.savefig(savepath, dpi=600, bbox_inches="tight")
    return fig, axes


