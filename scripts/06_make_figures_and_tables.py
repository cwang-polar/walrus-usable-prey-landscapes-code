def plot_si_6panels(
    site: str,
    ship_windows: Sequence[str],
    pure_dict: Mapping[str, Sequence[Mapping[str, object]]],
    df_ice_only: pd.DataFrame,
    df_cross: pd.DataFrame,
    savepath: str | Path | None = None,
):
    """Appendix S7/S8: beta-by-window ice+ship sensitivity matrix."""

    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(3, 2, figsize=(10, 12), sharex=True, sharey=True)
    betas = [0.3, 0.5, 0.8]
    alphas = [0.3, 0.5, 0.8]
    colors = {0.3: "#ff9896", 0.5: "#d62728", 0.8: "#8c564b"}
    panel_letters = ["(a)", "(b)", "(c)", "(d)", "(e)", "(f)"]

    for row_idx, beta in enumerate(betas):
        for col_idx, window in enumerate(ship_windows):
            ax = axes[row_idx, col_idx]
            ax.text(0.04, 0.96, panel_letters[row_idx * 2 + col_idx], transform=ax.transAxes, fontweight="bold", va="top")
            t_pure, a_pure = get_pure_robust(pure_dict, window)
            if len(t_pure):
                ax.plot(t_pure * 100, a_pure * 100, color="black", lw=2.0, label="Pure biomass")
            t_ice, a_ice = get_ship_ice_robust(df_ice_only, site, beta, 0.0, window)
            if len(t_ice):
                ax.plot(t_ice * 100, a_ice * 100, color="#1f77b4", linestyle="--", lw=2.0, label="Ice-only")
            for alpha in alphas:
                t_ship, a_ship = get_ship_ice_robust(df_cross, site, beta, alpha, window)
                if len(t_ship):
                    ax.plot(t_ship * 100, a_ship * 100, color=colors[alpha], linestyle="-.", lw=1.5, label=f"alpha={alpha}")
            ax.set_title(f"{window.replace('_', '-')}\nbeta={beta}" if row_idx == 0 else f"beta={beta}")
            ax.set_xlim(0, 105)
            ax.set_ylim(0, 105)
            ax.grid(True, linestyle=":", alpha=0.5)
            if col_idx == 0:
                ax.set_ylabel("Minimum area (% of site)")
            if row_idx == 2:
                ax.set_xlabel("Target biomass threshold (%)")
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=5, bbox_to_anchor=(0.5, 0.97), frameon=False)
    plt.tight_layout(rect=[0, 0, 1, 0.97])
    if savepath is not None:
        plt.savefig(savepath, dpi=600, bbox_inches="tight", pad_inches=0.02)
    return fig, axes


def plot_figure_s1_baseline_spatial_efficiency(
    min_area_curves: Mapping[str, Sequence[Mapping[str, object]]],
    baseline_window: str,
    comparison_windows: Sequence[str],
    site_name: str,
    savepath: str | Path | None = None,
):
    """Appendix Figure S1: pure-biomass baseline spatial-efficiency differences."""

    import matplotlib.pyplot as plt

    baseline_thresholds, baseline_area = get_pure_robust(min_area_curves, baseline_window)
    fig, ax = plt.subplots(figsize=(7.5, 4.5))
    for window in comparison_windows:
        thresholds, area = get_pure_robust(min_area_curves, window)
        if len(thresholds) == 0:
            continue
        common = sorted(set(np.round(baseline_thresholds, 8)) & set(np.round(thresholds, 8)))
        if not common:
            continue
        base_lookup = dict(zip(np.round(baseline_thresholds, 8), baseline_area))
        comp_lookup = dict(zip(np.round(thresholds, 8), area))
        diff = np.array([comp_lookup[t] - base_lookup[t] for t in common])
        ax.plot(np.array(common) * 100, diff * 100, marker="o", linewidth=2, label=f"{window.replace('_', '-')} - {baseline_window.replace('_', '-')}")
    ax.axhline(0, color="black", linewidth=1, linestyle="--")
    ax.set_xlabel("Prey biomass threshold (%)")
    ax.set_ylabel("Difference in minimum area required (% of site)")
    ax.set_title(f"{site_name}: baseline spatial efficiency")
    ax.grid(True, alpha=0.3)
    ax.legend(frameon=False)
    plt.tight_layout()
    if savepath is not None:
        plt.savefig(savepath, dpi=600, bbox_inches="tight", pad_inches=0.02)
    return fig, ax


